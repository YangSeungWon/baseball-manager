"""
데이터 레이어. 게임 로직은 이 파일의 존재를 몰라도 돌아가야 한다.
표시용 이름만 담당하며, 시뮬레이션 계산에는 절대 관여하지 않는다.
나중에 실명 DB / 사용자 커스텀 DB로 통째로 교체 가능.
"""
import random

_SUR = ["강","고","곽","권","김","나","남","노","도","류","문","민","박","배","백",
        "서","석","성","손","송","신","심","안","양","엄","오","유","윤","이","임",
        "장","전","정","조","주","진","차","채","최","하","한","허","홍","황"]
_G1 = ["민","현","준","지","서","도","시","예","하","우","성","재","태","동","건",
       "규","승","한","진","윤","기","상","영","경","주","용","광"]
_G2 = ["우","호","준","현","석","진","수","훈","빈","한","성","재","혁",
       "찬","영","기","환","용","교","건","민","섭","철","원","열"]

_CITY = ["서울","인천","수원","대전","대구","부산","광주","울산","창원","전주","청주","춘천"]
_NICK = ["레이븐스","타이탄스","드래곤스","파이러츠","머스탱스","코메츠",
         "울브스","팰컨스","바이슨","스톰","레인저스","포세이돈"]


def make_person_name(rng: random.Random) -> str:
    return rng.choice(_SUR) + rng.choice(_G1) + rng.choice(_G2)


def make_team_names(n: int, rng: random.Random):
    cities = rng.sample(_CITY, n)
    nicks = rng.sample(_NICK, n)
    return [(c, f"{c} {k}") for c, k in zip(cities, nicks)]
